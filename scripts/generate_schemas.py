"""Write pob2-optimizer/pob2opt/schemas/v1 from the record dataclasses.

    python scripts/generate_schemas.py            # rewrite the files
    python scripts/generate_schemas.py --check    # fail if they are stale

``--check`` is what CI and tests/unit/test_p01_t01_schemas.py use. Run the
plain form after adding or changing a field in pob2opt/domain/records.py.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "pob2-optimizer"))

from pob2opt.domain.schema_gen import build_all  # noqa: E402
from pob2opt.domain.schemas import SCHEMA_DIR  # noqa: E402


def render(schema: dict) -> str:
    return json.dumps(schema, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report stale or missing files without writing")
    args = parser.parse_args(argv)

    schemas = build_all()
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    expected = {"%s.json" % kind: render(doc) for kind, doc in schemas.items()}

    on_disk = {p.name for p in SCHEMA_DIR.glob("*.json")}
    stale = sorted(on_disk - set(expected))
    problems: list[str] = ["%s is not a record kind" % name for name in stale]

    for name, text in sorted(expected.items()):
        path = SCHEMA_DIR / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            problems.append("%s is %s" % (name, "missing" if current is None
                                          else "out of date"))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote %s" % path.relative_to(REPO))

    if args.check:
        for problem in problems:
            print("stale schema: %s" % problem, file=sys.stderr)
        if problems:
            print("run: python scripts/generate_schemas.py", file=sys.stderr)
            return 1
        print("%d schema files match pob2opt/domain/records.py" % len(expected))
    elif stale:
        for name in stale:
            print("note: %s is not generated by this script" % name,
                  file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
